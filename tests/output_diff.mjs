import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {compareOutput, comparisonReport, comparable, tolerances} from '../site/output_diff.mjs';
const cases = JSON.parse(readFileSync(new URL('./output_diff_cases.json', import.meta.url), 'utf8'));
for (const c of cases) assert.equal(compareOutput(c.a, c.b, c.mode, c.atol || '0', c.rtol || '0').status, c.status, JSON.stringify(c));
for (const bad of ['-1', 'NaN', 'Infinity', '', 'garbage', '1e9999']) assert.throws(() => tolerances(bad));
assert.equal(compareOutput('x'.repeat(1000001), '', 'exact').status, 'Not comparable');
assert.equal(compareOutput('1 '.repeat(20001), '2', 'numeric').status, 'Not comparable');
const row = (compiler, stdout) => ({compiler, status: 'PASS', result: {ok: true, execution: {ok: true, exit_code: 0, stdout}}});
const first = row('gfortran', '1.0'), second = row('ifx', '1D0');
const failed = {...row('bad', '1D0'), status: 'FAIL'};
const truncated = row('truncated', '1D0'); truncated.result.execution.truncated = true;
assert.equal(comparable(failed), false); assert.equal(comparable(truncated), false);
assert.equal(comparable({compiler: 'compile-only', status: 'PASS', result: {ok: true, build: {ok: true}}}), false);
const report = comparisonReport([failed, first, second, truncated], 'numeric');
assert.match(report, /Reference: gfortran/); assert.match(report, /ifx: Numeric match/);
assert.match(report, /bad: Not comparable/); assert.match(report, /truncated: Not comparable/);
assert.match(comparisonReport([first, second], 'numeric', '0', '0', 'ifx'), /Reference: ifx/);
assert.match(comparisonReport([first, second], 'numeric', '0', '0', 'missing'), /unavailable/);
console.log('Output diff shared fixtures, exact decimals, tolerances, labels, special values, and eligibility passed.');
