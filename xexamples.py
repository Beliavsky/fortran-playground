"""Generate the browser example catalog from single-file Fortran programs."""
import json
from pathlib import Path
import re


EXTENSIONS = {'.f90', '.f95', '.f03', '.f08'}


def generate_examples(site: Path) -> None:
    examples = {}
    labels = {}
    for path in sorted((site / 'examples').glob('*'), key=lambda p: p.name):
        if not path.is_file() or path.suffix.lower() not in EXTENSIONS:
            continue
        if path.stem in examples:
            raise ValueError(f'Duplicate example name: {path.stem}')
        source = path.read_text(encoding='utf-8-sig')
        title = re.search(r'^\s*!\s*Example:\s*(\S[^\r\n]*)', source, re.MULTILINE)
        examples[path.stem] = source
        labels[path.stem] = (title.group(1).strip() if title else
                             re.sub(r'^\d+[_-]', '', path.stem).replace('_', ' ').replace('-', ' '))
    content = ('// Generated by xexamples.py; edit site/examples/ instead.\n'
               f'export const examples = {json.dumps(examples, ensure_ascii=True, indent=2)};\n'
               f'export const exampleLabels = {json.dumps(labels, ensure_ascii=True, indent=2)};\n')
    target = site / 'examples.generated.mjs'
    if not target.exists() or target.read_text(encoding='utf-8') != content:
        target.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    generate_examples(Path(__file__).resolve().parent / 'site')
